"""Generate the contract matrix skeleton from packages/contracts (T017/T018).

Owner and consumers are inferred from which services mention the schema name in their source;
the result is committed and then curated by hand. shortcut: text search, not an import graph;
upgrade if owners come out wrong.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from .contracts_gate import HTTP, schema_files

OWNERSHIP = {
    "siweb-connector": "integration", "inventory-service": "inventory", "forecast-service": "forecasting",
    "procurement-service": "procurement", "siweb-cost-writer": "costwrite", "api-bff": "bff",
}
EVENT_PREFIX_OWNER = {
    "forecast": "forecast-service", "inventory": "inventory-service", "procurement": "procurement-service",
    "siweb.sync": "siweb-connector", "siweb.cost": "siweb-cost-writer",
}
SHARED = "agent-00"


def _service_text(root: Path) -> dict[str, str]:
    out = {}
    for service in OWNERSHIP:
        parts = []
        for f in sorted((root / "services" / service / "src").rglob("*.py")):
            parts.append(f.read_text(encoding="utf-8", errors="replace"))
        out[service] = "\n".join(parts)
    return out


HTTP = ("get", "post", "put", "patch", "delete")


def endpoint_entries(openapi: dict) -> list[dict]:
    """Gateway endpoints from its OpenAPI document (T049). status is `draft`: no schema file lets the gate detect changes."""
    return [{"name": f"{method.upper()} {path}", "kind": "endpoint", "version": 1, "owner": SHARED, "consumers": ["web"],
             "status": "draft"}
            for path, ops in sorted(openapi["paths"].items()) for method in HTTP if method in ops]


def _existing_endpoints(root: Path) -> list[dict]:
    path = root / "docs/architecture/integration/contract-matrix.json"
    if not path.exists():
        return []
    return [e for e in json.loads(path.read_text())["entries"] if e["kind"] == "endpoint"]


def _existing_schemas(root: Path) -> dict[tuple, dict]:
    path = root / "docs/architecture/integration/contract-matrix.json"
    if not path.exists():
        return {}
    return {(e["kind"], e["name"], e["version"]): e for e in json.loads(path.read_text())["entries"] if e["kind"] != "endpoint"}


def generate(root: Path, endpoints: list[dict] | None = None) -> dict:
    """Owners are heuristic for new schemas; an owner, status or successor already in the file (curated by hand) wins."""
    text = _service_text(root)
    curated = _existing_schemas(root)
    entries = []
    for path, (kind, name, version) in schema_files(root).items():
        needles = {name, f"{name}.v{version}", f"{name}.v{version}.schema.json"}
        users = sorted(s for s, t in text.items() if any(n in t for n in needles))
        owner = SHARED
        if kind == "event":
            owner = next((o for p, o in EVENT_PREFIX_OWNER.items() if name.startswith(p)), SHARED)
        elif len(users) == 1:
            owner = users[0]
        old = curated.get((kind, name, version), {})
        owner = old.get("owner", owner)
        entry = {"name": name, "kind": kind, "version": version, "schema_path": path, "owner": owner,
                 "consumers": [u for u in users if u != owner], "status": old.get("status", "frozen")}
        if "superseded_by" in old:
            entry["superseded_by"] = old["superseded_by"]
        entries.append(entry)
    entries += endpoints if endpoints is not None else _existing_endpoints(root)  # regeneration keeps curated endpoints
    return {"matrix_version": 1, "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "schema_ownership": OWNERSHIP, "entries": entries}


def render(matrix: dict) -> str:
    """Markdown view of contract-matrix.json (T020): who owns, versions and consumes each interface."""
    lines = ["# Contract matrix", "", "Generated by `python -m gates matrix-md`; edit `contract-matrix.json`, not this file.", "",
             "The gateway is `services/api-bff`.", "", "## Database schema ownership", "",
             "| Service | Schema |", "|---|---|", *(f"| {s} | {d} |" for s, d in matrix["schema_ownership"].items()), "",
             "## Interfaces", "", "| Name | Kind | Version | Owner | Consumers | Status |", "|---|---|---|---|---|---|"]
    lines += [f"| `{e['name']}` | {e['kind']} | v{e['version']} | {e['owner']} | {', '.join(e['consumers']) or '-'} | {e['status']} |"
              for e in sorted(matrix["entries"], key=lambda e: (e["kind"], e["name"], e["version"]))]
    return "\n".join(lines) + "\n"


def write(root: Path, openapi: dict | None = None) -> Path:
    path = root / "docs/architecture/integration/contract-matrix.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    endpoints = endpoint_entries(openapi) if openapi else None
    path.write_text(json.dumps(generate(root, endpoints), indent=2) + "\n", encoding="utf-8")
    return path
