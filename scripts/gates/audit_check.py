"""Audit evidence checker (T009, spec FR-001): every `path:line` must exist, and `complete` needs test evidence."""

from __future__ import annotations

import re
from pathlib import Path

TEST_PATH = re.compile(r"(^|/)(tests?|e2e)/|(^|/)test_[^/]*$|\.(test|spec)\.[jt]sx?$")


def render(audit: dict) -> str:
    """Markdown view of feature-status.json (T012): summary, table, reuse list, gaps by owner."""
    feats = audit["features"]
    counts = {s: sum(f["status"] == s for f in feats) for s in ("complete", "partial", "broken", "missing", "unverified")}
    lines = [f"# Feature status (audited at commit `{audit['audited_commit']}`)", "",
             "Generated by `python -m gates audit-md`; edit `feature-status.json`, not this file.", "",
             "Status: " + ", ".join(f"{k} {v}" for k, v in counts.items()), "",
             "| Feature | Status | Owner | Evidence | Notes |", "|---|---|---|---|---|"]
    lines += [f"| {f['title']} | {f['status']} | {f['owner']} | {'<br>'.join(f'`{e}`' for e in f['evidence'])} | {f.get('notes', '')} |"
              for f in feats]
    gaps: dict[str, list[str]] = {}
    for f in feats:
        if f["status"] != "complete":
            gaps.setdefault(f["owner"], []).append(f"{f['id']} ({f['status']})")
    lines += ["", "## Gaps by owner", *(f"- **{o}**: {', '.join(g)}" for o, g in sorted(gaps.items())),
              "", "## Reuse", "Features flagged `reuse` have working code that domain agents extend instead of rewriting: "
              + ", ".join(f["id"] for f in feats if f.get("reuse")) + "."]
    return "\n".join(lines) + "\n"


def check(root: Path, audit: dict) -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    for f in audit["features"]:
        if f["id"] in seen:
            problems.append(f"{f['id']}: duplicate id")
        seen.add(f["id"])
        has_test = False
        for ref in f["evidence"]:
            path, _, line = ref.rpartition(":")
            file = root / path
            if not file.is_file():
                problems.append(f"{f['id']}: evidence file missing: {path}")
                continue
            count = len(file.read_text(encoding="utf-8", errors="replace").splitlines())
            if not 1 <= int(line) <= max(count, 1):
                problems.append(f"{f['id']}: evidence line {line} outside {path} ({count} lines)")
            has_test = has_test or bool(TEST_PATH.search(path))
        if f["status"] == "complete" and not has_test:
            problems.append(f"{f['id']}: complete needs test evidence, otherwise mark it unverified")
    return problems
